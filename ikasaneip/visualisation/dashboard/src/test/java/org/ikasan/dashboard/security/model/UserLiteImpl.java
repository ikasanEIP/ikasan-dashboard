package org.ikasan.dashboard.security.model;

import org.ikasan.spec.security.model.UserLite;

public class UserLiteImpl implements UserLite
{
    private Object id;
    private String username;
    private String password;
    private String email;
    private String firstName;
    private String surname;
    private String department;
    private boolean enabled;
    private long previousAccessTimestamp;

    @Override
    public boolean isAccountNonExpired()
    {
        return true;
    }

    @Override
    public boolean isAccountNonLocked()
    {
        return true;
    }

    @Override
    public boolean isCredentialsNonExpired()
    {
        return true;
    }

    @Override
    public boolean isEnabled()
    {
        return enabled;
    }

    @Override
    public String getUsername()
    {
        return username;
    }

    @Override
    public void setUsername(String username)
    {
        this.username = username;
    }

    @Override
    public String getPassword()
    {
        return password;
    }

    @Override
    public void setPassword(String password)
    {
        this.password = password;
    }

    @Override
    public String getEmail()
    {
        return email;
    }

    @Override
    public void setEmail(String email)
    {
        this.email = email;
    }

    @Override
    public void setEnabled(boolean enabled)
    {
        this.enabled = enabled;
    }

    @Override
    public Object getId()
    {
        return id;
    }

    @Override
    public String getFirstName()
    {
        return firstName;
    }

    @Override
    public void setFirstName(String firstName)
    {
        this.firstName = firstName;
    }

    @Override
    public String getSurname()
    {
        return surname;
    }

    @Override
    public void setSurname(String surname)
    {
        this.surname = surname;
    }

    @Override
    public String getDepartment()
    {
        return department;
    }

    @Override
    public void setDepartment(String department)
    {
        this.department = department;
    }

    @Override
    public long getPreviousAccessTimestamp()
    {
        return previousAccessTimestamp;
    }

    @Override
    public void setPreviousAccessTimestamp(long previousAccessTimestamp)
    {
        this.previousAccessTimestamp = previousAccessTimestamp;
    }
}
