package org.ikasan.dashboard.ui.visualisation.scheduler.service;

public class Draw2dAdapterException extends RuntimeException {

    public Draw2dAdapterException() {
    }

    public Draw2dAdapterException(String message) {
        super(message);
    }

    public Draw2dAdapterException(String message, Throwable cause) {
        super(message, cause);
    }

    public Draw2dAdapterException(Throwable cause) {
        super(cause);
    }

    public Draw2dAdapterException(String message, Throwable cause, boolean enableSuppression, boolean writableStackTrace) {
        super(message, cause, enableSuppression, writableStackTrace);
    }
}
